// 使用 JSZip 官方浏览器产物，选择 MIT 许可并保留原版权声明。
const fs = require('node:fs');
const path = require('node:path');

function buildZipVendor() {
    const root = path.resolve(__dirname, '..');
    const zipRoot = path.dirname(require.resolve('jszip/package.json'));
    const core = fs.readFileSync(path.join(zipRoot, 'dist/jszip.min.js'), 'utf8');
    const license = fs.readFileSync(path.join(zipRoot, 'LICENSE.markdown'), 'utf8').split('GPL version 3')[0].trim();
    fs.writeFileSync(path.join(root, 'public/vendor/jszip.min.js'),
        `${core}\n/*!\nGenerated by npm run build:zip; do not edit.\n${license}\n*/\n`);
}

if (require.main === module) buildZipVendor();
module.exports = { buildZipVendor };
